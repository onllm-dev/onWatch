  function normalizeLanguage(value) {
    if (typeof value !== 'string') return '';
    const normalized = value.trim().replace('_', '-').toLowerCase();
    if (normalized === 'en' || normalized.startsWith('en-')) return 'en';
    if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN';
    return '';
  }

  function readStoredLanguage() {
    try {
      return normalizeLanguage(localStorage.getItem(STORAGE_KEY));
    } catch (e) {
      return '';
    }
  }

  function detectBrowserLanguage() {
    const candidates = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language || ''];
    for (const candidate of candidates) {
      const language = normalizeLanguage(candidate);
      if (language) return language;
    }
    return DEFAULT_LANGUAGE;
  }

  let currentLanguage = readStoredLanguage() || detectBrowserLanguage();

  function interpolate(message, params) {
    if (!params) return message;
    return message.replace(/\{([a-zA-Z0-9_]+)\}/g, function (match, name) {
      return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match;
    });
  }

  function t(key, params) {
    const fallback = MESSAGES.en[key] || key;
    const message = (MESSAGES[currentLanguage] && MESSAGES[currentLanguage][key]) || fallback;
    return interpolate(message, params);
  }

  function translateElement(element) {
    const textKey = element.getAttribute('data-i18n');
    if (textKey) element.textContent = t(textKey);

    const attributes = [
      ['data-i18n-placeholder', 'placeholder'],
      ['data-i18n-aria-label', 'aria-label'],
      ['data-i18n-title', 'title'],
    ];
    attributes.forEach(function (entry) {
      const key = element.getAttribute(entry[0]);
      if (key) element.setAttribute(entry[1], t(key));
    });
  }

  function translate(root) {
    const scope = root && typeof root.querySelectorAll === 'function' ? root : document;
    if (scope.nodeType === 1 && scope.matches('[data-i18n], [data-i18n-placeholder], [data-i18n-aria-label], [data-i18n-title]')) {
      translateElement(scope);
    }
    scope.querySelectorAll('[data-i18n], [data-i18n-placeholder], [data-i18n-aria-label], [data-i18n-title]')
      .forEach(translateElement);
  }

  function syncSelectors() {
    document.querySelectorAll('[data-language-selector]').forEach(function (selector) {
      if (selector.value !== currentLanguage) selector.value = currentLanguage;
      if (selector.dataset.languageBound !== 'true') {
        selector.dataset.languageBound = 'true';
        selector.addEventListener('change', function () {
          setLanguage(selector.value);
        });
      }
    });
  }

  function setLanguage(language, options) {
    const settings = options || {};
    const normalized = normalizeLanguage(language) || DEFAULT_LANGUAGE;
    const changed = currentLanguage !== normalized;
    currentLanguage = normalized;
    document.documentElement.lang = normalized;
    document.documentElement.setAttribute('data-language', normalized);

    if (settings.persist !== false) {
      try {
        localStorage.setItem(STORAGE_KEY, normalized);
      } catch (e) {
        // Browser privacy settings may disable localStorage. Language still applies for this page.
      }
    }

    translate(document);
    syncSelectors();
    if (changed && settings.emit !== false) {
      document.dispatchEvent(new CustomEvent('onwatch:languagechange', {
        detail: { language: normalized },
      }));
    }
    return normalized;
  }

  function getLanguage() {
    return currentLanguage;
  }

  function getLocale() {
    return currentLanguage === 'zh-CN' ? 'zh-CN' : 'en-US';
  }

  window.onWatchI18n = Object.freeze({
    supportedLanguages: SUPPORTED_LANGUAGES,
    normalizeLanguage: normalizeLanguage,
    getLanguage: getLanguage,
    getLocale: getLocale,
    setLanguage: setLanguage,
    t: t,
    translate: translate,
  });

  setLanguage(currentLanguage, { persist: false, emit: false });

  if (typeof MutationObserver !== 'undefined') {
    const observer = new MutationObserver(function (mutations) {
      mutations.forEach(function (mutation) {
        mutation.addedNodes.forEach(function (node) {
          if (node.nodeType === 1) translate(node);
        });
      });
      syncSelectors();
    });
    observer.observe(document.documentElement, { childList: true, subtree: true });
  }
